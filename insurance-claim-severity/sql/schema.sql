-- Batch provenance -> claim outcomes -> one-to-one feature records.
-- Composite keys allow the same claim ID in different versioned datasets.
PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS ingestion_batches (
    batch_id INTEGER PRIMARY KEY,
    source TEXT NOT NULL,
    sha256 TEXT NOT NULL UNIQUE,
    row_count INTEGER NOT NULL CHECK(row_count > 0),
    quality_json TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS claims (
    batch_id INTEGER NOT NULL REFERENCES ingestion_batches(batch_id),
    claim_id INTEGER NOT NULL CHECK(claim_id > 0),
    loss REAL NOT NULL CHECK(loss >= 0),
    PRIMARY KEY(batch_id, claim_id)
);
